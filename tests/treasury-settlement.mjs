import assert from 'node:assert/strict';
import { build } from 'esbuild';
const compiled=await build({entryPoints:['src/api/rgs/mockClient.ts'],bundle:true,write:false,platform:'node',format:'esm',alias:{'@':'./src'},define:{'import.meta.env.DEV':'true'}});
const {createMockRgsClient}=await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
const saved=new Map();
globalThis.sessionStorage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v)};
const book={id:33,payoutMultiplier:2000,events:[{type:'treasury',amount:2000,rewards:[{kind:'cash',value:400},{kind:'multiplier',value:1},{kind:'cash',value:600}],uncappedAmount:2000}]};
globalThis.fetch=async()=>({ok:true,json:async()=>book});
const first=createMockRgsClient();
const auth=await first.authenticate();
const stake=auth.config.defaultBetLevel;
const played=await first.play({amount:stake,mode:'base'});
assert.equal(played.balance.amount,auth.balance.amount-stake);
const resumed=createMockRgsClient();
assert.equal((await resumed.authenticate()).round.payout,20*stake);
await assert.rejects(()=>resumed.play({amount:stake,mode:'base'}));
const expected=played.balance.amount+20*stake;
assert.equal((await resumed.endRound()).balance.amount,expected);
assert.equal((await resumed.endRound()).balance.amount,expected);
const complete=await createMockRgsClient().authenticate();
assert.equal(complete.round,null);
assert.equal(complete.balance.amount,expected);
console.log('Treasury: active round restored, one debit and one settlement, no duplicate payout after reload.');
