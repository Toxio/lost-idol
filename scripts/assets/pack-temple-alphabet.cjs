const sharp = require('sharp');
const fs = require('node:fs');
const path = require('node:path');
async function main() {
 const source = process.argv[2];
 if (!source) throw Error('Pass the generated transparent atlas path');
 const {data,info} = await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789$.,+%!';
 const regions={},layers=[];
 for(let i=0;i<chars.length;i++) {
  const col=i%7,row=Math.floor(i/7);
  const xs=[0,210,425,640,850,1070,1290,1514];
  const x0=xs[col],x1=xs[col+1];
  const ys=[0,173,345,520,691,863,1039];
  const y0=ys[row],y1=ys[row+1];
  let left=x1,top=y1,right=x0,bottom=y0;
  for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++)if(data[(y*info.width+x)*4+3]>100){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  const height=bottom-top+1,width=right-left+1;
  const targetHeight='.,'.includes(chars[i])?48:144;
  const targetWidth=Math.round(width*targetHeight/height);
  const png=await sharp(source).extract({left,top,width,height}).resize(targetWidth,targetHeight).png().toBuffer();
  const x=col*200+8,y=row*160+8;
  layers.push({input:png,left:x,top:y+144-targetHeight});
  regions[chars[i]]=[x,y,targetWidth,144];
 }
 const dest='src/assets/big-win';
 await sharp({create:{width:1400,height:960,channels:4,background:'#0000'}}).composite(layers).webp({lossless:true}).toFile(path.join(dest,'lost-idol-glyphs.webp'));
 fs.writeFileSync(path.join(dest,'glyphRegions.ts'),'// Generated by scripts/assets/pack-temple-alphabet.cjs\nexport const GLYPH_ATLAS_WIDTH = 1400;\nexport const GLYPH_ATLAS_HEIGHT = 960;\nexport const glyphRegions: Record<string, [number, number, number, number]> = '+JSON.stringify(regions,null,2)+';\n');
}
main().catch(e=>{console.error(e);process.exit(1)});
